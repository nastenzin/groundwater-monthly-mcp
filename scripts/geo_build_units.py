def close_ring(ring):
    ring = [(round(float(x), 3), round(float(y), 3)) for x, y in ring]
    if ring[0] != ring[-1]:
        ring.append(ring[0])
    return ring


def build_geometry(polygons):
    if len(polygons) == 1:
        return {"type": "Polygon", "coordinates": [close_ring(polygons[0])]}
    return {
        "type": "MultiPolygon",
        "coordinates": [[close_ring(ring)] for ring in polygons],
    }


def main() -> int:
    assert len(UNITS) == 24, f"应有 24 个单元，实际 {len(UNITS)}"
    features = []
    groups: dict[str, int] = {}
    for uid, name, group, priority, provinces, polygons in UNITS:
        assert len(polygons) >= 1
        for ring in polygons:
            assert len(ring) >= 3, f"{name} 环顶点不足"
        features.append(
            {
                "type": "Feature",
                "properties": {
                    "id": uid,
                    "name": name,
                    "group": group,
                    "provinces": provinces,
                    "accuracy": "approximate",
                    "priority": priority,
                },
                "geometry": build_geometry(polygons),
            }
        )
        groups[group] = groups.get(group, 0) + 1

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        json.dumps(
            {"type": "FeatureCollection", "features": features},
            ensure_ascii=False,
            separators=(",", ":"),
        ),
        encoding="utf-8",
    )
    print(f"写出 {OUT} ({OUT.stat().st_size/1024:.1f} KB), {len(features)} 个单元")
    for group, count in groups.items():
        print(f"  {group}: {count}")
    return 0


